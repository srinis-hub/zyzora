
from abc import ABC, abstractmethod


class AIModel(ABC):

    def __init__(self, name, provider, temperature):

        if temperature < 0 or temperature > 1:
            raise ValueError("Temperature must be between 0 and 1.")        
        
        self.name = name
        self.provider = provider
        self.temperature = temperature

        pass

    def show_details(self):
        print(f"Model Name: {self.name}")
        print(f"Provider: {self.provider}")
        print(f"Temperature: {self.temperature}")

        pass

    @abstractmethod
    def generate_response(self, prompt):
        pass


    def validate_prompt(self, prompt):
        if not prompt or not prompt.strip():
            raise ValueError("Prompt cannot be empty.")


class GeminiModel(AIModel):

    def __init__(self, name, temperature):
        super().__init__(name, "Gemini", temperature)
        pass

    def generate_response(self, prompt):
        self.validate_prompt(prompt)
        return f"Gemini model '{self.name}' response to prompt: '{prompt}' with temperature {self.temperature}"

       


class OpenAIModel(AIModel):

    def __init__(self, name, temperature):
        super().__init__(name, "OpenAI", temperature)
        pass

    def generate_response(self, prompt):
        self.validate_prompt(prompt)
        return f"OpenAI model '{self.name}' response to prompt: '{prompt}' with temperature {self.temperature}"
   


gemini = GeminiModel("gemini-2.5-flash", 0.7)
openai = OpenAIModel("gpt-4.1", 0.9)


models = [gemini, openai]


for model in models:

    model.show_details()

    print(model.generate_response("Response Generated by the model"))
